import Foundation

protocol ReportServicing {
    func generateValidationReportHTML(
        manifest: BuildManifest,
        validation: ValidationSummary,
        inspection: PackageInspectionReport?,
        signatureVerification: String?,
        notarizationValidation: String?
    ) -> String
}

/// Renders the human-readable `Validation-Report.html` that accompanies every
/// build, combining the requirements panel's results with facts pulled from
/// the actual built artifact (`PackageInspectionReport`) rather than restating
/// the configuration the user asked for. Every dynamic value is HTML-escaped
/// before interpolation — this file is opened in a real browser, and package
/// names/descriptions originate from Homebrew metadata this app doesn't control.
final class ReportService: ReportServicing {

    func generateValidationReportHTML(
        manifest: BuildManifest,
        validation: ValidationSummary,
        inspection: PackageInspectionReport?,
        signatureVerification: String?,
        notarizationValidation: String?
    ) -> String {
        var html = "<!DOCTYPE html>\n<html>\n<head>\n<meta charset=\"utf-8\">\n"
        html += "<title>Validation Report — \(escape(manifest.applicationName))</title>\n"
        html += stylesheet
        html += "</head>\n<body>\n"
        html += "<h1>\(escape(manifest.applicationName)) \(escape(manifest.applicationVersion))</h1>\n"
        html += "<p class=\"meta\">Built \(isoDate(manifest.buildDate)) &middot; \(escape(manifest.packagingMode.rawValue)) &middot; \(escape(manifest.architecture.rawValue)) &middot; Overall: <span class=\"badge \(validation.overallStatus.rawValue)\">\(escape(validation.overallStatus.rawValue.uppercased()))</span></p>\n"

        html += "<h2>Requirements</h2>\n<table>\n<tr><th>Check</th><th>Status</th><th>Detail</th></tr>\n"
        for check in validation.checks {
            html += "<tr class=\"\(check.status.rawValue)\"><td>\(escape(check.name))</td><td>\(escape(check.status.rawValue.uppercased()))</td><td>\(escape(check.detail))</td></tr>\n"
        }
        html += "</table>\n"

        html += "<h2>Package Artifact</h2>\n<ul>\n"
        html += "<li>Configured identifier: \(escape(manifest.packageIdentifier))</li>\n"
        html += "<li>Configured receipt version: \(escape(manifest.packageReceiptVersion))</li>\n"
        if let inspection {
            html += "<li>Inspected identifier: \(escape(inspection.identifier ?? "unknown"))</li>\n"
            html += "<li>Inspected version: \(escape(inspection.version ?? "unknown"))</li>\n"
            html += "<li>Install location: \(escape(inspection.installLocation ?? "unknown"))</li>\n"
            html += "<li>Payload files: \(inspection.payloadFileCount)</li>\n"
            html += "<li>Scripts included: \(inspection.scriptNames.isEmpty ? "none" : escape(inspection.scriptNames.joined(separator: ", ")))</li>\n"
            html += "<li>Package size: \(formattedSize(inspection.sizeBytes))</li>\n"
            html += "<li>pkgutil signature check: \(escape(inspection.signatureStatus))</li>\n"
        } else {
            html += "<li class=\"unavailable\">Package inspection unavailable for this build.</li>\n"
        }
        html += "</ul>\n"

        html += "<h2>Signing &amp; Notarization</h2>\n<ul>\n"
        if let identity = manifest.signingIdentity {
            html += "<li>Signed with: \(escape(identity))</li>\n"
        } else {
            html += "<li>Signed: no</li>\n"
        }
        html += "<li>Signature verification: \(escape(signatureVerification ?? "not run"))</li>\n"
        html += "<li>Notarization validation: \(escape(notarizationValidation ?? "not run"))</li>\n"
        html += "</ul>\n"

        html += "<h2>Output Files</h2>\n<ul>\n"
        for file in manifest.outputFiles {
            html += "<li>\(escape(file))</li>\n"
        }
        html += "</ul>\n"

        html += "<p class=\"footer\">Generated by App Package Builder \(escape(manifest.builderApplicationVersion))</p>\n"
        html += "</body>\n</html>\n"
        return html
    }

    private func escape(_ value: String) -> String {
        value
            .replacingOccurrences(of: "&", with: "&amp;")
            .replacingOccurrences(of: "<", with: "&lt;")
            .replacingOccurrences(of: ">", with: "&gt;")
            .replacingOccurrences(of: "\"", with: "&quot;")
            .replacingOccurrences(of: "'", with: "&#39;")
    }

    private func isoDate(_ date: Date) -> String {
        let formatter = DateFormatter()
        formatter.dateStyle = .medium
        formatter.timeStyle = .short
        return escape(formatter.string(from: date))
    }

    private func formattedSize(_ bytes: Int64) -> String {
        ByteCountFormatter.string(fromByteCount: bytes, countStyle: .file)
    }

    private var stylesheet: String {
        """
        <style>
        body { font-family: -apple-system, BlinkMacSystemFont, sans-serif; margin: 2rem; color: #1c1c1e; background: #fff; }
        h1 { margin-bottom: 0.2rem; }
        .meta { color: #666; margin-top: 0; }
        table { border-collapse: collapse; width: 100%; margin-bottom: 1.5rem; }
        th, td { padding: 6px 10px; border-bottom: 1px solid #ddd; text-align: left; }
        tr.fail td:nth-child(2) { color: #c0392b; font-weight: 600; }
        tr.warning td:nth-child(2) { color: #b9770e; font-weight: 600; }
        tr.pass td:nth-child(2) { color: #1e8449; font-weight: 600; }
        .badge { padding: 2px 8px; border-radius: 6px; font-weight: 600; }
        .badge.pass { background: #d4efdf; color: #1e8449; }
        .badge.warning { background: #fdebd0; color: #b9770e; }
        .badge.fail { background: #f5b7b1; color: #922b21; }
        .badge.checking { background: #eee; color: #555; }
        .unavailable { color: #888; font-style: italic; }
        .footer { color: #999; font-size: 0.8rem; margin-top: 2rem; }
        </style>
        """
    }
}
