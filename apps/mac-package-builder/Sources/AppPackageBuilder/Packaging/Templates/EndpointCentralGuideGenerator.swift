import Foundation

/// Generates `EndpointCentral-Deployment-Guide.txt`. Direct upload to
/// Endpoint Central is intentionally not implemented yet — this is a
/// documented future extension point (see README "Known Limitations").
enum EndpointCentralGuideGenerator {
    static func generate(
        configuration: PackageConfiguration,
        packageInfo: BrewPackageInfo,
        packagePath: URL,
        detectionScriptPath: URL,
        uninstallScriptPath: URL
    ) -> String {
        let logPath = "/Library/Logs/AppPackageBuilder/\(configuration.homebrewToken.replacingOccurrences(of: "@", with: "-at-")).log"
        return """
        ManageEngine Endpoint Central — Deployment Guide
        Generated by App Package Builder \(BuildManifest.currentBuilderVersion)

        Package filename:       \(packagePath.lastPathComponent)
        Package identifier:     \(configuration.packageIdentifier)
        Package version:        \(configuration.packageVersion)
        Application version:    \(packageInfo.version)
        Architecture:            \(configuration.architecture.displayName)
        Packaging mode:          \(configuration.packagingMode.displayName)

        Installation command (silent):
          sudo installer -pkg "\(packagePath.lastPathComponent)" -target /

        Detection script:
          \(detectionScriptPath.lastPathComponent)
          Exit 0  = installed and meets the required version
          Exit 1  = not installed
          Exit 2  = installed but version mismatch

        Uninstall command:
          sudo bash "\(uninstallScriptPath.lastPathComponent)"

        Expected exit codes (postinstall):
          0  success
          1  no console user logged in
          2  Homebrew missing (Online Installer mode only)
          3  install command failed
          4-5 service failed to start
          6  installed check failed post-install

        Log path on target Mac (Online Installer mode):
          \(logPath)

        Required profiles:
          PPPC / Notification / other profiles: verify manually per application — not auto-detected.

        Network requirements:
          \(configuration.packagingMode == .onlineInstaller
              ? "Target Mac needs internet access to Homebrew's bottle/cask CDN at install time."
              : "None — this package is self-contained and installs offline.")

        Recommended test procedure:
          1. Deploy to a single pilot Mac via Software Deployment > Packages > Add Package > Mac.
          2. Confirm the detection script reports installed/not-installed correctly before rollout.
          3. Review \(logPath.isEmpty ? "the postinstall log" : logPath) after a test install.
          4. Roll out via Software Deployment > Deployment > Self-Service Portal once verified.

        Validation report:
          \(configuration.homebrewToken)-Validation-Report.html (open in a browser) — requirement
          checks, inspected package contents, and signing/notarization verification for this build.

        Note: Direct upload to Endpoint Central from App Package Builder is not implemented in
        this release. Upload the generated .pkg manually via the Endpoint Central console.
        """
    }
}
