// Generates the package artifacts (scripts + metadata). Everything is a pure function of the job so the output is
// reproducible and unit-testable. Every embedded value has already passed configProblems(); PowerShell literals
// are additionally escaped here as defence in depth.

import { join } from 'node:path'
import { writeFileSync } from 'node:fs'
import { jobDir } from './workspace.js'
import type { PackageConfig, PackageJob } from './types.js'

export const ARTIFACT_NAMES = ['install.ps1', 'uninstall.ps1', 'detection.ps1', 'package-info.json', 'README.md', 'validation-report.json'] as const
export type ArtifactName = typeof ARTIFACT_NAMES[number]

/** PowerShell single-quoted literal: only ' needs escaping (doubled). */
export const psq = (s: string): string => `'${s.replace(/'/g, "''")}'`

/** Splits a validated command into program + the raw argument remainder (quotes preserved in the remainder). */
export function splitCommand(cmd: string): { file: string; args: string } {
  const t = cmd.trim()
  if (t.startsWith('"')) {
    const end = t.indexOf('"', 1)
    return { file: t.slice(1, end), args: t.slice(end + 1).trim() }
  }
  const sp = t.search(/\s/)
  return sp < 0 ? { file: t, args: '' } : { file: t.slice(0, sp), args: t.slice(sp + 1).trim() }
}

const isAppx = (c: PackageConfig): boolean => /\.(msix|appx)$/i.test(c.setupFile)

const HEADER = (c: PackageConfig, what: string): string =>
  `# ${what} — ${c.appName} ${c.version} (${c.architecture})\n# Generated by Windows Package Builder. Not validated until a Windows worker reports success.\n`

function runCommandScript(c: PackageConfig, command: string, label: string): string {
  const { file, args } = splitCommand(command)
  const isSetup = file.replace(/\\/g, '/').replace(/^\.\//, '').toLowerCase() === c.setupFile.toLowerCase()
  const target = isSetup ? `Join-Path $PSScriptRoot ${psq(c.setupFile)}` : `[Environment]::ExpandEnvironmentVariables(${psq(file)})`
  return `${HEADER(c, label)}$ErrorActionPreference = 'Stop'
$file = ${target}
$arguments = ${psq(args)}
if ($arguments) {
    $proc = Start-Process -FilePath $file -ArgumentList $arguments -Wait -PassThru -NoNewWindow
} else {
    $proc = Start-Process -FilePath $file -Wait -PassThru -NoNewWindow
}
exit $proc.ExitCode
`
}

export function installScript(c: PackageConfig): string {
  if (isAppx(c)) {
    return `${HEADER(c, 'Install')}$ErrorActionPreference = 'Stop'
Add-AppxPackage -Path (Join-Path $PSScriptRoot ${psq(c.setupFile)})
exit 0
`
  }
  return runCommandScript(c, c.installCommand, 'Install')
}

export function uninstallScript(c: PackageConfig): string {
  if (isAppx(c)) {
    const name = c.detection.type === 'appx-package' ? c.detection.value ?? '' : ''
    return `${HEADER(c, 'Uninstall')}$ErrorActionPreference = 'Stop'
$package = Get-AppxPackage -AllUsers -Name ${psq(name)}
if ($package) { $package | Remove-AppxPackage -AllUsers }
exit 0
`
  }
  return runCommandScript(c, c.uninstallCommand, 'Uninstall')
}

/** Intune script detection: the app is "detected" only if the script writes to STDOUT and exits 0. */
export function detectionScript(c: PackageConfig): string {
  const d = c.detection
  const min = d.minVersion ? psq(d.minVersion) : '$null'
  const versionCheck = `function Test-MinVersion($found, $min) {
    if (-not $min) { return $true }
    try { return ([version]($found -replace '[^0-9.].*$','')) -ge ([version]($min -replace '[^0-9.].*$','')) } catch { return $true }
}
`
  const hit = `Write-Output 'Detected'\nexit 0\n`
  const miss = `exit 1\n`
  const head = HEADER(c, 'Detection')
  const uninstallRoots = `$roots = @('HKLM:\\SOFTWARE\\Microsoft\\Windows\\CurrentVersion\\Uninstall', 'HKLM:\\SOFTWARE\\WOW6432Node\\Microsoft\\Windows\\CurrentVersion\\Uninstall')\n`
  switch (d.type) {
    case 'msi-product-code':
      return `${head}${versionCheck}$min = ${min}\n${uninstallRoots}foreach ($root in $roots) {
    $key = Join-Path $root ${psq(d.value ?? '')}
    if (Test-Path -LiteralPath $key) {
        $v = (Get-ItemProperty -LiteralPath $key -ErrorAction SilentlyContinue).DisplayVersion
        if (Test-MinVersion $v $min) { ${hit.replace(/\n/g, '; ').trim()} }
    }
}
${miss}`
    case 'appx-package':
      return `${head}${versionCheck}$min = ${min}
$package = Get-AppxPackage -AllUsers -Name ${psq(d.value ?? '')} -ErrorAction SilentlyContinue | Select-Object -First 1
if ($package -and (Test-MinVersion $package.Version.ToString() $min)) { ${hit.replace(/\n/g, '; ').trim()} }
${miss}`
    case 'file-exists':
      return `${head}$path = [Environment]::ExpandEnvironmentVariables(${psq(d.value ?? '')})
if (Test-Path -LiteralPath $path) { ${hit.replace(/\n/g, '; ').trim()} }
${miss}`
    case 'registry-uninstall':
      return `${head}${versionCheck}$min = ${min}\n${uninstallRoots}$name = ${psq(d.value ?? '')}
foreach ($root in $roots) {
    if (-not (Test-Path -LiteralPath $root)) { continue }
    foreach ($item in Get-ChildItem -LiteralPath $root -ErrorAction SilentlyContinue) {
        $p = Get-ItemProperty -LiteralPath $item.PSPath -ErrorAction SilentlyContinue
        if ($p.DisplayName -and $p.DisplayName -like "$name*" -and (Test-MinVersion $p.DisplayVersion $min)) { ${hit.replace(/\n/g, '; ').trim()} }
    }
}
${miss}`
    default:
      return `${head}# No detection method is configured. Package creation is blocked until one is chosen.\nexit 1\n`
  }
}

export function packageInfo(job: PackageJob): object {
  return {
    schema: 'ito-win-package/1',
    generatedAt: new Date().toISOString(),
    jobId: job.id,
    state: job.state,
    validated: job.validation?.outcome === 'validated',
    source: job.source,
    analysis: job.analysis && {
      installerFile: job.analysis.installerFile, installerKind: job.analysis.installerKind, tech: job.analysis.tech,
      commandConfidence: job.analysis.commands.confidence, confidence: job.analysis.confidence,
      productCode: job.analysis.productCode, upgradeCode: job.analysis.upgradeCode,
      packageFamilyName: job.analysis.packageFamilyName, signature: job.analysis.signature,
    },
    config: job.config,
    output: job.output,
  }
}

export function readme(job: PackageJob): string {
  const c = job.config
  if (!c) return '# Package not configured\n'
  const status = job.validation?.outcome === 'validated'
    ? '**Validated on Windows** (install, detection and uninstall all passed).'
    : job.validation?.outcome === 'failed'
      ? '**Windows validation FAILED.** Do not deploy until resolved.'
      : '**Package Created / Windows Installation Not Tested.**'
  return `# ${c.appName} ${c.version} (${c.architecture})

${status}

| Field | Value |
|---|---|
| Publisher | ${c.publisher} |
| Setup file | ${c.setupFile} |
| Install behavior | ${c.installBehavior} |
| Source SHA-256 | ${job.source.sha256} |
| Signature | ${job.analysis?.signature.status ?? 'unknown'}${job.analysis?.signature.signer ? ` (${job.analysis.signature.signer})` : ''} |

## Commands
- Install: \`${c.installCommand}\`
- Uninstall: \`${c.uninstallCommand}\`

## Detection
\`${c.detection.type}\`${c.detection.value ? ` — ${c.detection.value}` : ''}${c.detection.minVersion ? ` (minimum ${c.detection.minVersion})` : ''}

Test on a pilot device before any wider use.
`
}

export function validationReport(job: PackageJob): object {
  return job.validation ?? {
    outcome: 'not-tested', at: null, steps: [],
    message: 'Package Created / Windows Installation Not Tested. No Windows worker has run install, detection and uninstall.',
  }
}

export function generateArtifacts(job: PackageJob): Record<ArtifactName, string> {
  const c = job.config
  if (!c) throw new Error('Job has no configuration.')
  return {
    'install.ps1': installScript(c),
    'uninstall.ps1': uninstallScript(c),
    'detection.ps1': detectionScript(c),
    'package-info.json': JSON.stringify(packageInfo(job), null, 2),
    'README.md': readme(job),
    'validation-report.json': JSON.stringify(validationReport(job), null, 2),
  }
}

export function writeArtifacts(job: PackageJob): ArtifactName[] {
  const files = generateArtifacts(job)
  const dir = join(jobDir(job.id), 'artifacts')
  for (const name of ARTIFACT_NAMES) writeFileSync(join(dir, name), files[name], { encoding: 'utf-8', mode: 0o600 })
  return [...ARTIFACT_NAMES]
}
